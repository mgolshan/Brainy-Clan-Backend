<?php

namespace App\Modules\Content\Generation;

use App\Modules\ChallengeTypes\ChallengeTypeRegistry;
use App\Modules\ChallengeTypes\Handlers\WordPuzzle;
use Illuminate\Contracts\JsonSchema\JsonSchema;
use Illuminate\JsonSchema\Types\Type;
use InvalidArgumentException;
use Throwable;

/**
 * What the AI batch generator can produce: one entry per challenge type (and word puzzle
 * variant). Each entry has a structured-output schema for one item, type-specific prompt
 * guidance, and a mapping from the model's item to payload + answer, built through the
 * challenge type handler's own `fromFlatRow()` (the same path as the CSV importer) and then
 * validated by the handler. Sudoku and Math Sprint are generated by code, never by AI.
 */
class GenerationTypes
{
    /** Public-domain rule of thumb: author died at least this many years ago (life + 70). */
    public const int PUBLIC_DOMAIN_YEARS = 71;

    public const array LABELS = [
        'multiple_choice' => 'Multiple choice',
        'wisdom_card' => 'Wisdom card (original or public-domain quote)',
        'word_puzzle:anagram' => 'Word puzzle: anagram',
        'word_puzzle:missing_letter' => 'Word puzzle: missing letter',
        'word_puzzle:word_search' => 'Word puzzle: word search',
    ];

    public function __construct(private readonly ChallengeTypeRegistry $registry) {}

    /**
     * Generation types whose challenge type is active, key => label.
     *
     * @return array<string, string>
     */
    public function options(): array
    {
        return array_filter(
            self::LABELS,
            fn (string $key) => $this->registry->isActive(self::split($key)[0]),
            ARRAY_FILTER_USE_KEY,
        );
    }

    /**
     * "word_puzzle:anagram" → ["word_puzzle", "anagram"]; "multiple_choice" → ["multiple_choice", null].
     *
     * @return array{0: string, 1: string|null}
     */
    public static function split(string $key): array
    {
        if (! array_key_exists($key, self::LABELS)) {
            throw new InvalidArgumentException("Unknown generation type [{$key}].");
        }

        $parts = explode(':', $key, 2);

        return [$parts[0], $parts[1] ?? null];
    }

    public static function key(string $typeKey, ?string $variant): string
    {
        return $variant !== null ? "{$typeKey}:{$variant}" : $typeKey;
    }

    /**
     * JSON schema of one generated item.
     *
     * @return array<string, Type>
     */
    public function itemSchema(string $key, JsonSchema $schema): array
    {
        $common = [
            'difficulty' => $schema->integer()->description('1 (very easy) to 10 (expert), within the requested range.')->required(),
            'explanation' => $schema->string()->description('One or two sentences shown after answering: why the answer is right, a short fact.')->required(),
        ];

        $choices = fn (array $ids) => array_merge(
            collect($ids)->mapWithKeys(fn (string $id) => ["choice_{$id}" => $schema->string()->description("Answer option {$id}.")->required()])->all(),
            ['correct' => $schema->string()->enum($ids)->description('Id of the single correct option. Vary its position across items.')->required()],
        );

        return match ($key) {
            'multiple_choice' => [
                'question' => $schema->string()->description('The question, one sentence, ends with "?" where natural.')->required(),
                ...$choices(['a', 'b', 'c', 'd']),
                ...$common,
            ],
            'wisdom_card' => [
                'origin' => $schema->string()->enum(['original', 'public_domain_quote'])->description('"original" = written by you for this app (no author); "public_domain_quote" = a verbatim quote whose author died long ago.')->required(),
                'card_text' => $schema->string()->description('The card: a short saying or idea (max ~30 words).')->required(),
                'card_author' => $schema->string()->nullable()->description('Quote author; null for original cards.')->required(),
                'card_source' => $schema->string()->nullable()->description('Work the quote comes from (e.g. "Meditations"); null for original cards.')->required(),
                'author_death_year' => $schema->integer()->nullable()->description('Year the quote author died (negative for BC); null for original cards.')->required(),
                'question' => $schema->string()->description('Comprehension question about the card, e.g. "What is the main idea?"')->required(),
                ...$choices(['a', 'b', 'c']),
                ...$common,
            ],
            'word_puzzle:anagram' => [
                'word' => $schema->string()->description('The answer word, one word, letters only.')->required(),
                'hint' => $schema->string()->description('A short clue that does not contain the word.')->required(),
                'also_accepted' => $schema->array()->items($schema->string())->description('Other real words made of exactly the same letters (often empty).')->required(),
                ...$common,
            ],
            'word_puzzle:missing_letter' => [
                'word' => $schema->string()->description('The answer word, one word, letters only, at least 4 letters.')->required(),
                'hint' => $schema->string()->description('A short clue that does not contain the word.')->required(),
                ...$common,
            ],
            'word_puzzle:word_search' => [
                'theme' => $schema->string()->description('Theme of the word list, e.g. "Ocean animals".')->required(),
                'words' => $schema->array()->items($schema->string())->description('5–8 single words on the theme, letters only, 3–8 letters each.')->required(),
                ...$common,
            ],
            default => throw new InvalidArgumentException("Unknown generation type [{$key}]."),
        };
    }

    /**
     * Type-specific instructions for the prompt.
     */
    public function guidance(string $key): string
    {
        return match ($key) {
            'multiple_choice' => 'Multiple choice: one clearly correct answer and three plausible but clearly wrong options of similar length and style. No "all of the above" / "none of the above". The question must be answerable without an image.',
            'wisdom_card' => 'Wisdom cards: prefer ORIGINAL cards (origin "original", author/source/death year null) written in plain words for the age range. Only use a real quote (origin "public_domain_quote") when it is verbatim, reliably attributed, and the author died more than '.self::PUBLIC_DOMAIN_YEARS.' years ago; give author, work and death year. Never quote modern authors, living people, song lyrics, films or book summaries. The question checks understanding of the card; three options, one correct.',
            'word_puzzle:anagram' => 'Anagrams: a common, age-appropriate word on the category theme. The letters are scrambled by the app. List in also_accepted any other common words using exactly the same letters.',
            'word_puzzle:missing_letter' => 'Missing letter: a common, age-appropriate word on the category theme (the app hides one or two letters). The hint must make the word guessable.',
            'word_puzzle:word_search' => 'Word search: one themed word list per item; words are hidden in a grid by the app. Use common words with letters only (no spaces or hyphens).',
            default => '',
        };
    }

    /**
     * Turn one model item into payload + answer through the handler, or return why it is dropped.
     *
     * @param  array<string, mixed>  $raw
     * @return array{payload: array<string, mixed>, answer: array<string, mixed>}|list<string> list = errors
     */
    public function build(string $key, array $raw, int $difficulty): array
    {
        [$typeKey, $variant] = self::split($key);
        $handler = $this->registry->get($typeKey);
        $errors = $this->contentRuleErrors($key, $raw);

        if ($errors !== []) {
            return $errors;
        }

        try {
            $built = $handler->fromFlatRow($this->flatRow($key, $raw, $difficulty));
        } catch (Throwable $e) {
            return [$e->getMessage()];
        }

        $explanation = trim((string) ($raw['explanation'] ?? ''));

        if ($explanation !== '') {
            $built['answer']['explanation'] = $explanation;
        }

        if ($variant !== null) {
            $built['payload']['variant'] = $variant;
        }

        $validation = $handler->validate($built['payload'], $built['answer']);

        if ($validation !== []) {
            return collect($validation)->flatMap(fn (array $messages, string $field) => array_map(fn (string $m) => "{$field}: {$m}", $messages))->values()->all();
        }

        return $built;
    }

    /**
     * Rules the handler cannot know (content and legal rules).
     *
     * @param  array<string, mixed>  $raw
     * @return list<string>
     */
    private function contentRuleErrors(string $key, array $raw): array
    {
        if ($key !== 'wisdom_card') {
            return [];
        }

        if (($raw['origin'] ?? null) === 'original') {
            return filled($raw['card_author'] ?? null) ? ['An original card must not name an author.'] : [];
        }

        if (($raw['origin'] ?? null) !== 'public_domain_quote') {
            return ['origin must be "original" or "public_domain_quote".'];
        }

        if (blank($raw['card_author'] ?? null) || blank($raw['card_source'] ?? null)) {
            return ['A quote needs its author and source.'];
        }

        $died = $raw['author_death_year'] ?? null;

        if (! is_int($died) || $died > (int) now()->year - self::PUBLIC_DOMAIN_YEARS) {
            return ['Quote author is not clearly public domain (death year '.(is_int($died) ? $died : 'unknown').').'];
        }

        return [];
    }

    /**
     * The handler's CSV columns, filled from the model item.
     *
     * @param  array<string, mixed>  $raw
     * @return array<string, mixed>
     */
    private function flatRow(string $key, array $raw, int $difficulty): array
    {
        $string = fn (string $field) => is_scalar($raw[$field] ?? null) ? trim((string) $raw[$field]) : '';
        $choices = fn (array $ids) => collect($ids)->mapWithKeys(fn (string $id) => ["choice_{$id}" => $string("choice_{$id}")])->all();

        return match ($key) {
            'multiple_choice' => ['question' => $string('question'), ...$choices(['a', 'b', 'c', 'd']), 'correct' => $string('correct')],
            'wisdom_card' => [
                'card_text' => $string('card_text'), 'card_author' => $string('card_author'), 'card_source' => $string('card_source'),
                'question' => $string('question'), ...$choices(['a', 'b', 'c']), 'correct' => $string('correct'),
            ],
            'word_puzzle:anagram' => [
                'variant' => 'anagram', 'word' => $string('word'), 'hint' => $string('hint'),
                'also_accepted' => implode(' ', array_filter((array) ($raw['also_accepted'] ?? []), 'is_string')),
            ],
            'word_puzzle:missing_letter' => [
                'variant' => 'missing_letter', 'word' => $string('word'), 'hint' => $string('hint'),
                'pattern' => WordPuzzle::hideLetters($string('word'), $difficulty >= 6 ? 2 : 1, $string('word')),
            ],
            'word_puzzle:word_search' => [
                'variant' => 'word_search',
                'words' => implode(' ', array_filter((array) ($raw['words'] ?? []), 'is_string')),
                'size' => $difficulty <= 3 ? 6 : ($difficulty <= 6 ? 8 : 10),
            ],
            default => throw new InvalidArgumentException("Unknown generation type [{$key}]."),
        };
    }
}
